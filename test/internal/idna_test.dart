  test('rejected labels throw', () {
    for (final label in rejected) {
      expect(() => toAscii(label), throwsA(isA<IdnaException>()),
          reason: label);
    }
  });

  group('separators and empty labels follow the JVM', () {
    test('a single trailing dot is kept', () {
      expect(toAscii('a.'), 'a.');
      expect(toAscii('a.b.'), 'a.b.');
      expect(toAscii('.'), '.');
    });

    test('an empty label anywhere else is rejected', () {
      for (final input in ['..', '...', '.a', 'a..b', '.a.b']) {
        expect(() => toAscii(input), throwsA(isA<IdnaException>()),
            reason: input);
      }
    });

    test('all four RFC 3490 separators are recognised', () {
      // FULL STOP, IDEOGRAPHIC, FULLWIDTH, HALFWIDTH IDEOGRAPHIC
      for (final sep in [0x002E, 0x3002, 0xFF0E, 0xFF61]) {
        expect(isLabelSeparator(sep), isTrue);
        final host = 'a${String.fromCharCode(sep)}b';
        expect(toAscii(host), 'a.b', reason: 'U+${sep.toRadixString(16)}');
      }
      expect(isLabelSeparator(0x002C), isFalse);
    });
  });

  group('nameprep behaviours worth naming', () {
    test('full case folding maps sharp s to ss', () {
      // The reason Dart's toLowerCase is not enough: it leaves U+00DF alone,
      // which would make this a different host from strasse.de.
      expect(
          toAscii(String.fromCharCodes([0x73, 0x74, 0x72, 0x61, 0xDF, 0x65])),
          'strasse');
    });

    test('an already-encoded label passes through', () {
      expect(toAscii('xn--caf-dma'), 'xn--caf-dma');
    });

    test('ASCII is returned unchanged', () {
      expect(toAscii('example'), 'example');
      expect(toAscii('EXAMPLE'), 'EXAMPLE', reason: 'ASCII case is not folded');
    });

    test('an over-long label is rejected', () {
      expect(() => toAscii('a' * 64), throwsA(isA<IdnaException>()));
      expect(toAscii('a' * 63), 'a' * 63);
    });

    test('mixed-direction labels are rejected', () {
      // U+2135 ALEF SYMBOL is bidi class L, but NFKC maps it to Hebrew Alef,
      // which is class R - so this is a mixed-direction label after all.
      expect(
        () => toAscii(String.fromCharCodes([0x61, 0x2135, 0x62])),
        throwsA(isA<IdnaException>()),
      );
    });
  });

  group('punycode', () {
    test('pure ASCII round-trips through the delimiter form', () {
      expect(punycodeEncode('abc'), 'abc-');
      expect(punycodeDecode('abc-'), 'abc');
    });

    test('encode and decode are inverses for the JVM vectors', () {
      for (final (label, ace) in vectors) {
        // Only labels we actually encoded round-trip: an input that was already
        // ASCII (`xn--already`) is passed through untouched, never punycoded.
        if (!ace.startsWith(acePrefix)) continue;
        if (label.codeUnits.every((c) => c <= 0x7F)) continue;
        final suffix = ace.substring(acePrefix.length);
        expect(punycodeDecode(suffix), nameprep(label), reason: ace);
        expect(punycodeEncode(nameprep(label)), suffix, reason: ace);
      }
    });

    test('malformed input throws', () {
      expect(() => punycodeDecode('abc-!'), throwsA(isA<PunycodeException>()));
    });
  });
